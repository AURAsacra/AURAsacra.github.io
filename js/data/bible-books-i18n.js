export function parseScriptureReference(citation) {
  if (!citation) return { bookId: 'matt', chapter: 5, verse: 3 };
  const clean = citation.trim();
  const lower = clean.toLowerCase();

  let matchedBookId = null;
  for (const item of TITLE_TO_BOOK_ID) {
    if (lower.startsWith(item.title) || lower.includes(` ${item.title} `) || lower.includes(`${item.title} `)) {
      matchedBookId = item.id;
      break;
    }
  }

  // Chapter and verse extraction (e.g. "5:3", "5:3-12", "5, 3")
  let chapter = 1;
  let verse = 1;
  const numMatch = clean.match(/(\d+)(?:[:.,\s]+(\d+))?/);
  if (numMatch) {
    chapter = parseInt(numMatch[1], 10) || 1;
    if (numMatch[2]) {
      verse = parseInt(numMatch[2], 10) || 1;
    }
  }

  return {
    bookId: matchedBookId || 'matt',
    chapter,
    verse
  };
}

export function formatScriptureReference(bookId, chapter, verse, versionOrLang = 'it') {
  const title = getLocalizedBookTitle(bookId, versionOrLang);
  if (verse) {
    return `${title} ${chapter}:${verse}`;
  }
  return `${title} ${chapter}`;
}

export function localizeScriptureCitation(citation, targetVersionOrLang = 'it') {
  const parsed = parseScriptureReference(citation);
  return formatScriptureReference(parsed.bookId, parsed.chapter, parsed.verse, targetVersionOrLang);
}
